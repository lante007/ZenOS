'use strict';

const express = require('express');
const router = express.Router();
const { requireRoles } = require('../middleware/permissions');
const db = require('../services/db');
const {
  generateCanonicalSynthesis,
  transformToStrategicSynthesis,
} = require('../../src/claude-classifier');

router.post('/generate',
  requireRoles(
    'ORGANISATION_LEAD',
    'EVIDENCE_ANALYST'
  ),
  async (req, res, next) => {
    try {
      const { record_ids } = req.body;
      const tenant = req.tenant;

      if (!Array.isArray(record_ids) ||
          record_ids.length < 1) {
        return res.status(400).json({
          error: 'record_ids must be an array ' +
            'with at least one record',
        });
      }
      if (record_ids.length > 10) {
        return res.status(400).json({
          error: 'Maximum 10 records per synthesis',
        });
      }

      // Load full record data for each ID.
      const records = await db.getRecordsByIds(
        tenant, record_ids
      );

      if (!records || records.length === 0) {
        return res.status(404).json({
          error: 'No records found for provided IDs',
        });
      }

      // Canonical-synthesis-plus-transformer architecture, same pattern as
      // the six Knowledge Products personas: ensure every selected record
      // has a canonical synthesis (cached, reused if already generated by
      // any persona for this record version), then pass ONLY that curated,
      // already-disciplined array into the cross-record transformer. Never
      // raw records, never full document text, and no independent
      // re-synthesis of individual records.
      const canonicalSyntheses = await Promise.all(
        records.map(r => generateCanonicalSynthesis(r, tenant.slug))
      );
      const recordMetas = records.map(r => ({
        id: r.id,
        programme_name: r.programme_name,
      }));

      const parsed = await transformToStrategicSynthesis(
        canonicalSyntheses, recordMetas
      );

      // Save to zenex.syntheses.
      const synthesisTitle = records
        .map(r => r.programme_name)
        .join(' + ')
        .slice(0, 200);

      const saved = await db.saveSynthesis(tenant, {
        title: synthesisTitle,
        record_ids: record_ids,
        record_count: records.length,
        findings: parsed.findings || [],
        evidence_gaps: parsed.evidence_gaps || [],
        leverage_points: parsed.leverage_points || [],
        cross_patterns: parsed.cross_patterns || [],
      });

      return res.json({
        success: true,
        synthesis_id: saved.id,
        title: synthesisTitle,
        record_ids: record_ids,
        record_count: records.length,
        findings: parsed.findings || [],
        evidence_gaps: parsed.evidence_gaps || [],
        leverage_points:
          parsed.leverage_points || [],
        cross_patterns:
          parsed.cross_patterns || [],
        generated_at: new Date().toISOString(),
      });

    } catch (err) {
      next(err);
    }
  }
);

// GET saved synthesis by ID.
router.get('/:id',
  requireRoles(
    'ORGANISATION_LEAD',
    'EVIDENCE_ANALYST',
    'COMMUNICATIONS',
    'CEO_EXEC'
  ),
  async (req, res, next) => {
    try {
      const synthesis = await db.getSynthesis(
        req.tenant, req.params.id
      );
      if (!synthesis) {
        return res.status(404).json({
          error: 'Synthesis not found',
        });
      }
      return res.json(synthesis);
    } catch (err) {
      next(err);
    }
  }
);

// GET list of syntheses for tenant.
router.get('/',
  requireRoles(
    'ORGANISATION_LEAD',
    'EVIDENCE_ANALYST'
  ),
  async (req, res, next) => {
    try {
      const list = await db.listSyntheses(
        req.tenant
      );
      return res.json(list);
    } catch (err) {
      next(err);
    }
  }
);

// POST confirm a synthesis.
router.post('/:id/confirm',
  requireRoles('ORGANISATION_LEAD'),
  async (req, res, next) => {
    try {
      const updated = await db.confirmSynthesis(
        req.tenant,
        req.params.id,
        req.user?.sub
      );
      return res.json({
        success: true,
        synthesis: updated,
      });
    } catch (err) {
      next(err);
    }
  }
);

module.exports = router;
